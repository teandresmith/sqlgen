func TestParityFixtures(t *testing.T) {
	requireDatabases(t)

	tests := []struct {
		dialect string
		driver  string
		conn    func(t *testing.T) string
		reset   string
		ddl     string
		parser  func(t *testing.T) parser.Parser
	}{
		{
			dialect: "postgres",
			driver:  "pgx",
			conn:    func(*testing.T) string { return pgConnStr },
			reset:   pgParityFixtureReset,
			ddl:     pgParityFixture,
			parser:  func(*testing.T) parser.Parser { return postgres.New("public") },
		},
		{
			dialect: "mysql",
			driver:  "mysql",
			conn:    func(*testing.T) string { return mysqlConnStr },
			reset:   mysqlParityFixtureReset,
			ddl:     mysqlParityFixture,
			parser: func(t *testing.T) parser.Parser {
				p, err := mysql.New()
				if err != nil {
					t.Fatalf("mysql.New() error: %v", err)
				}
				return p
			},
		},
		{
			dialect: "sqlite",
			driver:  "sqlite",
			conn:    func(t *testing.T) string { return filepath.Join(t.TempDir(), "fixture.db") },
			ddl:     sqliteParityFixture,
			parser:  func(*testing.T) parser.Parser { return sqlite.New() },
		},
	}

	for _, tt := range tests {
		t.Run(tt.dialect, func(t *testing.T) {
			applyParityFixture(t, tt.driver, tt.conn(t), tt.reset, tt.ddl)

			p := tt.parser(t)
			for i, stmt := range splitStatements(tt.ddl) {
				if err := p.Parse(fmt.Sprintf("stmt_%02d.sql", i), []byte(stmt)); err != nil {
					t.Errorf("Parse(%q) error: %v", truncate(strings.Join(strings.Fields(stmt), " ")), err)
				}
			}
		})
	}
}

// applyParityFixture runs reset, then ddl one statement at a time, and runs
// reset again when the test ends.
func applyParityFixture(t *testing.T, driver, conn, reset, ddl string) {
	t.Helper()
	ctx := context.Background()

	db, err := sql.Open(driver, conn)
	if err != nil {
		t.Fatalf("opening %s: %v", driver, err)
	}
	t.Cleanup(func() {
		for _, stmt := range splitStatements(reset) {
			_, _ = db.ExecContext(ctx, stmt)
		}
		_ = db.Close()
	})

	for _, stmt := range splitStatements(reset + ";" + ddl) {
		if _, err := db.ExecContext(ctx, stmt); err != nil {
			t.Fatalf("applying %q: %v", truncate(strings.Join(strings.Fields(stmt), " ")), err)
		}
	}
}
