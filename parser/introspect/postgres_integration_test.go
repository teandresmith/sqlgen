// pgParityCase applies ddl, which creates its own schemas, then introspects
// those schemas with no search_path and parses ddl with the default schema
// public.
func pgParityCase(t *testing.T, reset, ddl string, schemas ...string) (parsed, introspected *parser.Schema) {
	t.Helper()
	applyParityFixture(t, "pgx", pgConnStr, reset, ddl)
	return parsePG(t, ddl), introspectPG(t, "", schemas...)
}

// introspectPG introspects schemas. connSuffix is appended to the connection
// string, as in "&search_path=…".
func introspectPG(t *testing.T, connSuffix string, schemas ...string) *parser.Schema {
	t.Helper()
	intro := introspect.NewPostgresIntrospector()
	defer intro.Close() //nolint:errcheck // test cleanup
	s := &parser.Schema{}
	if err := intro.Introspect(context.Background(), pgConnStr+connSuffix, s, introspect.IntrospectionOptions{Schemas: schemas}); err != nil {
		t.Fatalf("Introspect() error: %v", err)
	}
	return s
}

func parsePG(t *testing.T, ddl string) *parser.Schema {
	t.Helper()
	return parseStatements(t, postgres.New("public"), ddl)
}

// qualifiedColumnField returns field(column) for every column of the table schema.name.
func qualifiedColumnField(t *testing.T, s *parser.Schema, schema, name string, field func(parser.Column) string) map[string]string {
	t.Helper()
	for _, tbl := range s.Tables {
		if tbl.Schema != schema || tbl.Name != name {
			continue
		}
		out := make(map[string]string, len(tbl.Columns))
		for _, c := range tbl.Columns {
			out[c.Name] = field(c)
		}
		return out
	}
	t.Fatalf("table %s.%s not found", schema, name)
	return nil
}

func TestPostgresIntrospect_TypeCoverage(t *testing.T) {
	requireDatabases(t)
	ddl := `
CREATE SCHEMA pgi_types;
CREATE SCHEMA pgi_types2;
CREATE TYPE pgi_types.mood AS ENUM ('ok', 'meh');
CREATE TYPE pgi_types2.tone AS ENUM ('lo', 'hi');
CREATE DOMAIN pgi_types.posint AS integer CHECK (VALUE > 0);
CREATE DOMAIN pgi_types.tone_d AS pgi_types2.tone;
CREATE DOMAIN pgi_types2.mood_d AS pgi_types.mood;
CREATE DOMAIN pgi_types.mood_own AS pgi_types.mood;
CREATE TYPE pgi_types.addr AS (kind pgi_types.mood, kinds pgi_types.mood[], tone pgi_types2.tone, street varchar(40));
CREATE TABLE pgi_types.wide (
	id uuid PRIMARY KEY,
	price numeric(12,2),
	spaced numeric(10, 4),
	data bytea,
	dur interval,
	ip inet,
	small smallserial,
	med serial,
	ident_a int GENERATED ALWAYS AS IDENTITY,
	ident_b bigint GENERATED BY DEFAULT AS IDENTITY,
	m pgi_types.mood,
	d pgi_types.posint,
	ms pgi_types.mood[],
	vc varchar(255),
	ts timestamp(3),
	tstz timestamptz
)`
	parsed, introspected := pgParityCase(t, "DROP SCHEMA IF EXISTS pgi_types CASCADE; DROP SCHEMA IF EXISTS pgi_types2 CASCADE", ddl, "pgi_types", "pgi_types2")

	// Composite attributes and domain base types are written relative to the
	// type's own schema, like columns.
	for _, side := range []struct {
		name   string
		schema *parser.Schema
	}{{"parsed", parsed}, {"introspected", introspected}} {
		var attrs []parser.Attribute
		for _, ct := range side.schema.CompositeTypes {
			if ct.Name == "addr" {
				attrs = ct.Attributes
			}
		}
		wantAttrs := []parser.Attribute{{Name: "kind", Type: "mood"}, {Name: "kinds", Type: "mood[]"}, {Name: "tone", Type: "pgi_types2.tone"}, {Name: "street", Type: "varchar(40)"}}
		if diff := cmp.Diff(wantAttrs, attrs); diff != "" {
			t.Errorf("%s addr attributes mismatch (-want +got):\n%s", side.name, diff)
		}
		bases := make(map[string]string)
		for _, d := range side.schema.DomainTypes {
			bases[d.Schema+"."+d.Name] = d.BaseType
		}
		wantBases := map[string]string{"pgi_types.posint": "integer", "pgi_types.tone_d": "pgi_types2.tone", "pgi_types2.mood_d": "pgi_types.mood", "pgi_types.mood_own": "mood"}
		if diff := cmp.Diff(wantBases, bases); diff != "" {
			t.Errorf("%s domain base types mismatch (-want +got):\n%s", side.name, diff)
		}
	}

	wantTypes := map[string]string{
		"id": "uuid", "price": "numeric(12,2)", "spaced": "numeric(10,4)", "data": "bytea", "dur": "interval", "ip": "inet",
		"small": "smallint", "med": "integer", "ident_a": "integer", "ident_b": "bigint",
		"m": "mood", "d": "posint", "ms": "mood[]", "vc": "varchar(255)", "ts": "timestamp(3)", "tstz": "timestamptz",
	}
	wantAuto := map[string]string{
		"id": "false", "price": "false", "spaced": "false", "data": "false", "dur": "false", "ip": "false",
		"small": "true", "med": "true", "ident_a": "true", "ident_b": "true",
		"m": "false", "d": "false", "ms": "false", "vc": "false", "ts": "false", "tstz": "false",
	}
	typeOf := func(c parser.Column) string { return c.Type }
	autoOf := func(c parser.Column) string {
		if c.AutoIncrement {
			return "true"
		}
		return "false"
	}
	for _, side := range []struct {
		name   string
		schema *parser.Schema
	}{{"parsed", parsed}, {"introspected", introspected}} {
		if diff := cmp.Diff(wantTypes, qualifiedColumnField(t, side.schema, "pgi_types", "wide", typeOf)); diff != "" {
			t.Errorf("%s column types mismatch (-want +got):\n%s", side.name, diff)
		}
		if diff := cmp.Diff(wantAuto, qualifiedColumnField(t, side.schema, "pgi_types", "wide", autoOf)); diff != "" {
			t.Errorf("%s AutoIncrement mismatch (-want +got):\n%s", side.name, diff)
		}
	}
	assertSchemaParity(t, "postgres", parsed, introspected)
}

func TestPostgresIntrospect_Defaults(t *testing.T) {
	requireDatabases(t)
	ddl := `
CREATE SCHEMA pgi_defaults;
CREATE TYPE pgi_defaults.mood AS ENUM ('ok', 'meh');
CREATE TABLE pgi_defaults.d (
	id serial PRIMARY KEY,
	big bigserial,
	ident int GENERATED ALWAYS AS IDENTITY,
	lit text NOT NULL DEFAULT 'x',
	empty text DEFAULT '',
	quote text DEFAULT 'it''s',
	neg integer DEFAULT -1,
	negnum numeric DEFAULT -2.5,
	num numeric(12,2) DEFAULT 1.50,
	flag boolean DEFAULT true,
	created timestamptz DEFAULT now(),
	ts timestamptz DEFAULT CURRENT_TIMESTAMP,
	uid uuid DEFAULT gen_random_uuid(),
	m pgi_defaults.mood DEFAULT 'ok',
	tags text[] DEFAULT '{}',
	vc varchar(10) DEFAULT 'v',
	arr varchar(10)[] DEFAULT ARRAY['a', 'b'],
	at timestamp DEFAULT (now() AT TIME ZONE 'utc'),
	expr integer DEFAULT (1 + 2),
	big2 bigint DEFAULT 3000000000
)`
	parsed, introspected := pgParityCase(t, "DROP SCHEMA IF EXISTS pgi_defaults CASCADE", ddl, "pgi_defaults")

	want := map[string]string{
		"id": "", "big": "", "ident": "",
		"lit": "'x'", "empty": "''", "quote": "'it''s'", "neg": "-1", "negnum": "-2.5", "num": "1.50", "flag": "true",
		"created": "now()", "ts": "current_timestamp", "uid": "gen_random_uuid()", "m": "'ok'", "tags": "'{}'",
		"vc": "'v'", "arr": "ARRAY['a', 'b']", "at": "now() AT TIME ZONE 'utc'", "expr": "1 + 2", "big2": "3000000000",
	}
	defaultOf := func(c parser.Column) string { return c.Default }
	if diff := cmp.Diff(want, qualifiedColumnField(t, parsed, "pgi_defaults", "d", defaultOf)); diff != "" {
		t.Errorf("parsed defaults mismatch (-want +got):\n%s", diff)
	}
	if diff := cmp.Diff(want, qualifiedColumnField(t, introspected, "pgi_defaults", "d", defaultOf)); diff != "" {
		t.Errorf("introspected defaults mismatch (-want +got):\n%s", diff)
	}
	assertSchemaParity(t, "postgres", parsed, introspected)
}

func TestPostgresIntrospect_CheckAndDomainConstraints(t *testing.T) {
	requireDatabases(t)
	ddl := `
CREATE SCHEMA pgi_checks;
CREATE DOMAIN pgi_checks.posint AS integer CHECK (VALUE > 0);
CREATE DOMAIN pgi_checks.code AS varchar(20) CONSTRAINT code_format CHECK (VALUE ~ '^[a-z]+$') CHECK (VALUE <> '');
CREATE TYPE pgi_checks.mood AS ENUM ('ok', 'meh');
CREATE TABLE pgi_checks.c (
	id integer PRIMARY KEY,
	score pgi_checks.posint CHECK (score < 1000),
	code varchar(10) CHECK (code <> ''),
	c2 pgi_checks.code,
	m pgi_checks.mood CHECK (m <> 'meh'),
	price numeric(12,2) CHECK (price * 2 < 100),
	neg integer CHECK (neg > -5),
	d date CHECK (d > '2000-01-01'),
	CONSTRAINT always_ok CHECK (1 = 1),
	CONSTRAINT c2_len CHECK (length(c2) > 1)
);
ALTER TABLE pgi_checks.c ADD CONSTRAINT id_positive CHECK (id > 0) NOT VALID;
CREATE UNIQUE INDEX c_code_uq ON pgi_checks.c (code) WHERE code <> ''`
	parsed, introspected := pgParityCase(t, "DROP SCHEMA IF EXISTS pgi_checks CASCADE", ddl, "pgi_checks")

	wantChecks := map[string]string{
		"c_score_check": "score < 1000",
		"c_code_check":  "code <> ''",
		"c_m_check":     "m <> 'meh'",
		"c_price_check": "(price * 2) < 100",
		"c_neg_check":   "neg > -5",
		"c_d_check":     "d > '2000-01-01'",
		"always_ok":     "1 = 1",
		"c2_len":        "length(c2) > 1",
		"id_positive":   "id > 0",
	}
	wantDomains := map[string]string{
		"posint_check": "value > 0",
		"code_format":  "value ~ '^[a-z]+$'",
		"code_check":   "value <> ''",
	}
	for _, side := range []struct {
		name   string
		schema *parser.Schema
	}{{"parsed", parsed}, {"introspected", introspected}} {
		checks := make(map[string]string)
		where := ""
		for _, c := range findTable(t, side.schema, "c").Constraints {
			switch {
			case c.Type == parser.Check:
				checks[c.Name] = c.CheckExpression
			case c.Name == "c_code_uq":
				where = c.Where
			}
		}
		if diff := cmp.Diff(wantChecks, checks); diff != "" {
			t.Errorf("%s CHECK constraints mismatch (-want +got):\n%s", side.name, diff)
		}
		if where != "code <> ''" {
			t.Errorf("%s c_code_uq Where = %q, want %q", side.name, where, "code <> ''")
		}
		domains := make(map[string]string)
		for _, d := range side.schema.DomainTypes {
			for _, c := range d.Constraints {
				domains[c.Name] = c.CheckExpression
			}
		}
		if diff := cmp.Diff(wantDomains, domains); diff != "" {
			t.Errorf("%s domain constraints mismatch (-want +got):\n%s", side.name, diff)
		}
	}
	assertSchemaParity(t, "postgres", parsed, introspected)
}

// TestPostgresIntrospect_CatalogRewrites pins the expressions whose catalog
// text cannot be brought back to the DDL's: the catalog rewrites the operator,
// prints a date or time value in its own format, or holds a cast the DDL wrote
// that it would have added anyway. PRD §6.1 lists them.
func TestPostgresIntrospect_CatalogRewrites(t *testing.T) {
	requireDatabases(t)
	tests := []struct {
		name         string
		check        string
		parsed       string
		introspected string
	}{
		{name: "IN list", check: "n IN (1, 2)", parsed: "n IN (1, 2)", introspected: "n = ANY(ARRAY[1, 2])"},
		{name: "BETWEEN", check: "n BETWEEN 1 AND 10", parsed: "n BETWEEN 1 AND 10", introspected: "n >= 1 AND n <= 10"},
		{name: "SIMILAR TO", check: "s SIMILAR TO 'a%'", parsed: "s SIMILAR TO 'a%'", introspected: "s ~ similar_to_escape('a%')"},
		{name: "LIKE ESCAPE", check: "s LIKE 'a!%' ESCAPE '!'", parsed: "s LIKE pg_catalog.like_escape('a!%', '!')", introspected: "s ~~ like_escape('a!%', '!')"},
		{name: "time value", check: "ts > '2000-01-01'", parsed: "ts > '2000-01-01'", introspected: "ts > '2000-01-01 00:00:00+00'"},
		{name: "cast on a literal", check: "s <> 'x'::text", parsed: "s <> 'x'::text", introspected: "s <> 'x'"},
		{name: "cast to the implicit type", check: "v::text <> ''", parsed: "v::text <> ''", introspected: "v <> ''"},
	}
	ddl := "CREATE SCHEMA pgi_rewrites;\nCREATE TABLE pgi_rewrites.r (n integer, s text, v varchar(10), ts timestamptz"
	for i, tt := range tests {
		ddl += ",\n\tCONSTRAINT r_" + strconv.Itoa(i) + " CHECK (" + tt.check + ")"
	}
	ddl += "\n)"
	parsed, introspected := pgParityCase(t, "DROP SCHEMA IF EXISTS pgi_rewrites CASCADE", ddl, "pgi_rewrites")

	pTable, iTable := findTable(t, parsed, "r"), findTable(t, introspected, "r")
	for i, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			name := "r_" + strconv.Itoa(i)
			p, in := findConstraintByName(pTable.Constraints, name), findConstraintByName(iTable.Constraints, name)
			if p == nil || in == nil {
				t.Fatalf("constraint %s: parsed %v, introspected %v", name, p, in)
			}
			if p.CheckExpression != tt.parsed {
				t.Errorf("parsed %s = %q, want %q", tt.check, p.CheckExpression, tt.parsed)
			}
			if in.CheckExpression != tt.introspected {
				t.Errorf("introspected %s = %q, want %q", tt.check, in.CheckExpression, tt.introspected)
			}
		})
	}
}

// TestPostgresIntrospect_ExpressionIndexes pins that both sources skip an
// index with an expression part, unique or not, keep a column written as an
// expression, and keep the name a skipped index takes while its table exists.
func TestPostgresIntrospect_ExpressionIndexes(t *testing.T) {
	requireDatabases(t)
	ddl := `
CREATE SCHEMA pgi_exprix;
CREATE TABLE pgi_exprix.e (x text, a int, b int);
CREATE INDEX ON pgi_exprix.e (lower(x));
CREATE UNIQUE INDEX ux ON pgi_exprix.e (lower(x));
CREATE UNIQUE INDEX ux2 ON pgi_exprix.e (a, lower(x));
CREATE INDEX ix ON pgi_exprix.e (a, (a + b)) WHERE b > 0;
CREATE INDEX px ON pgi_exprix.e (((a)), b);
CREATE UNIQUE INDEX pcx ON pgi_exprix.e ((x COLLATE "C"));
CREATE TABLE pgi_exprix.n (x text, lower int, a int);
CREATE INDEX ON pgi_exprix.n (lower(x));
CREATE INDEX ON pgi_exprix.n (lower);
CREATE INDEX n_a_idx ON pgi_exprix.n (lower(x));
CREATE INDEX ON pgi_exprix.n (a);
CREATE TABLE pgi_exprix.d (x text, lower int);
CREATE INDEX ON pgi_exprix.d (lower(x));
DROP TABLE pgi_exprix.d;
CREATE TABLE pgi_exprix.d (x text, lower int);
CREATE INDEX ON pgi_exprix.d (lower);
CREATE TABLE pgi_exprix.r (x text, lower int);
CREATE INDEX ON pgi_exprix.r (lower(x));
ALTER TABLE pgi_exprix.r RENAME TO r2;
CREATE TABLE pgi_exprix.r (x text, lower int);
CREATE INDEX ON pgi_exprix.r (lower)`
	parsed, introspected := pgParityCase(t, "DROP SCHEMA IF EXISTS pgi_exprix CASCADE", ddl, "pgi_exprix")

	want := map[string][]parser.Constraint{
		"e": {
			{Name: "px", Type: parser.Index, Columns: []string{"a", "b"}, Method: "btree"},
			{Name: "pcx", Type: parser.Unique, Columns: []string{"x"}, Method: "btree"},
		},
		"n": {
			{Name: "n_a_idx1", Type: parser.Index, Columns: []string{"a"}, Method: "btree"},
			{Name: "n_lower_idx1", Type: parser.Index, Columns: []string{"lower"}, Method: "btree"},
		},
		"d": {{Name: "d_lower_idx", Type: parser.Index, Columns: []string{"lower"}, Method: "btree"}},
		"r": {{Name: "r_lower_idx1", Type: parser.Index, Columns: []string{"lower"}, Method: "btree"}},
	}
	for name, w := range want {
		got := findTable(t, introspected, name)
		sortConstraints(w)
		sortConstraints(got.Constraints)
		if diff := cmp.Diff(w, got.Constraints); diff != "" {
			t.Errorf("introspected %s constraints mismatch (-want +got):\n%s", name, diff)
		}
		for _, col := range got.Columns {
			if col.Unique != (name == "e" && col.Name == "x") {
				t.Errorf("introspected %s.%s: Unique = %v", name, col.Name, col.Unique)
			}
		}
	}
	assertSchemaParity(t, "postgres", parsed, introspected)
}

// TestPostgresIntrospect_BothModeExpressionIndexes checks `input.source: both`
// and `files` against the database once the migration is applied: an
// expression index or a view holds the name an unnamed index would take, and
// dropping a column drops the expression and partial indexes that read it,
// under its new name too.
func TestPostgresIntrospect_BothModeExpressionIndexes(t *testing.T) {
	requireDatabases(t)
	const (
		reset = "DROP SCHEMA IF EXISTS pgi_seedix CASCADE"
		base  = `CREATE SCHEMA pgi_seedix;
CREATE TABLE pgi_seedix.n (a int);
CREATE INDEX ON pgi_seedix.n ((a::text));
CREATE TABLE pgi_seedix.v (a int);
CREATE VIEW pgi_seedix.v_a_idx AS SELECT 1 AS x;
CREATE TABLE pgi_seedix.e (a int, x text, b int);
CREATE INDEX ON pgi_seedix.e (a, lower(x));
CREATE INDEX ON pgi_seedix.e (b) WHERE a > 0;
CREATE TABLE pgi_seedix.r (a int, x text);
CREATE INDEX ON pgi_seedix.r (a, lower(x))`
		migration = `CREATE INDEX ON pgi_seedix.n (a);
CREATE INDEX ON pgi_seedix.v (a);
ALTER TABLE pgi_seedix.e DROP COLUMN a;
ALTER TABLE pgi_seedix.e ADD COLUMN a int, ADD COLUMN lower int;
CREATE INDEX ON pgi_seedix.e (a, lower);
ALTER TABLE pgi_seedix.r RENAME COLUMN x TO y;
ALTER TABLE pgi_seedix.r DROP COLUMN y;
ALTER TABLE pgi_seedix.r ADD COLUMN lower int;
CREATE INDEX ON pgi_seedix.r (a, lower)`
	)
	applyParityFixture(t, "pgx", pgConnStr, reset, base)
	seeded := introspectPG(t, "", "pgi_seedix")
	p := postgres.New("public")
	if err := introspect.Merge(seeded, p, []string{writeMigration(t, migration)}); err != nil {
		t.Fatalf("Merge() error: %v", err)
	}

	applyParityFixture(t, "pgx", pgConnStr, "", migration)
	introspected := introspectPG(t, "", "pgi_seedix")

	want := map[string][]string{"n": {"n_a_idx1"}, "v": {"v_a_idx1"}, "e": {"e_a_lower_idx"}, "r": {"r_a_lower_idx"}}
	for name, w := range want {
		var got []string
		for _, c := range findTable(t, introspected, name).Constraints {
			got = append(got, c.Name)
		}
		if diff := cmp.Diff(w, got); diff != "" {
			t.Errorf("introspected %s index names mismatch (-want +got):\n%s", name, diff)
		}
	}
	assertSchemaParity(t, "postgres", p.Schema(), introspected)
	assertSchemaParity(t, "postgres", parsePG(t, base+";"+migration), introspected, pgSkippedStatementExceptions...)
}

// TestPostgresIntrospect_NoSearchPath introspects the probe fixture with no
// search_path and with search paths that put either schema first. Each gives
// the parsed schema: a type in the column's own schema is bare, and one in
// another schema is qualified (PRD §7.1).
func TestPostgresIntrospect_NoSearchPath(t *testing.T) {
	requireDatabases(t)
	applyParityFixture(t, "pgx", pgConnStr, pgParityFixtureReset, pgParityFixture)

	wantWarnings := []string{
		"CREATE TABLE events_2024 PARTITION OF events skipped in DDL file — the partitioned table is the entity",
		"CREATE TABLE events_2025 PARTITION OF events skipped in DDL file — the partitioned table is the entity",
		"CREATE VIEW active_users skipped in DDL file — use introspection or define the view in input.views",
	}
	wantTypes := map[string]string{"status": "status_enum", "statuses": "status_enum[]", "region": "probe_other.region", "score": "positive_int"}

	for _, conn := range []string{"", "&search_path=probe_app", "&search_path=probe_other,probe_app", "&search_path=probe_app,probe_other"} {
		t.Run("search_path"+conn, func(t *testing.T) {
			parsed := parsePG(t, pgParityFixture)
			introspected := introspectPG(t, conn, "probe_app", "probe_other")

			if diff := cmp.Diff(wantWarnings, parsed.Warnings); diff != "" {
				t.Errorf("parser warnings mismatch (-want +got):\n%s", diff)
			}
			typeOf := func(c parser.Column) string { return c.Type }
			got := qualifiedColumnField(t, introspected, "probe_app", "users", typeOf)
			for col, want := range wantTypes {
				if got[col] != want {
					t.Errorf("introspected users.%s Type = %q, want %q", col, got[col], want)
				}
			}
			// The parser skips views, so parity cannot check this one.
			viewTypes := make(map[string]string)
			for _, v := range introspected.Views {
				if v.Schema == "probe_app" && v.Name == "active_users" {
					for _, c := range v.Columns {
						viewTypes[c.Name] = c.Type
					}
				}
			}
			if diff := cmp.Diff(map[string]string{"id": "bigint", "status": "status_enum"}, viewTypes); diff != "" {
				t.Errorf("introspected active_users column types mismatch (-want +got):\n%s", diff)
			}
			assertSchemaParity(t, "postgres", parsed, introspected, pgSkippedStatementExceptions...)
		})
	}
}

func TestPostgresIntrospect_QuotedIdentifiers(t *testing.T) {
	requireDatabases(t)
	ddl := `
CREATE SCHEMA pgi_quoted;
CREATE TABLE pgi_quoted."UserAccounts" (
	"Id" integer PRIMARY KEY,
	"createdAt" timestamptz NOT NULL DEFAULT now(),
	"Email" varchar(100),
	CONSTRAINT "UserAccounts_Email_key" UNIQUE ("Email"),
	CONSTRAINT "Email_not_empty" CHECK ("Email" <> '')
);
CREATE TABLE pgi_quoted.posts (
	id integer PRIMARY KEY,
	"accountId" integer REFERENCES pgi_quoted."UserAccounts" ("Id"),
	CHECK ("accountId" > 0)
)`
	parsed, introspected := pgParityCase(t, "DROP SCHEMA IF EXISTS pgi_quoted CASCADE", ddl, "pgi_quoted")
	accounts := findTable(t, introspected, "UserAccounts")
	if c := findConstraintByName(accounts.Constraints, "Email_not_empty"); c == nil || c.CheckExpression != `"Email" <> ''` {
		t.Errorf(`introspected "Email_not_empty" = %+v, want CheckExpression "Email" <> ''`, c)
	}
	assertSchemaParity(t, "postgres", parsed, introspected)
}

// TestPostgresIntrospect_IncludeColumns pins that a standalone index lists
// only its key columns, not its INCLUDE payload, so a unique index with
// INCLUDE gives the conflict target PostgreSQL accepts.
func TestPostgresIntrospect_IncludeColumns(t *testing.T) {
	requireDatabases(t)
	ddl := `
CREATE SCHEMA pgi_include;
CREATE TABLE pgi_include.e (a int, b int, c int, d int);
CREATE INDEX inc ON pgi_include.e (a) INCLUDE (b);
CREATE UNIQUE INDEX u ON pgi_include.e (c) INCLUDE (d)`
	parsed, introspected := pgParityCase(t, "DROP SCHEMA IF EXISTS pgi_include CASCADE", ddl, "pgi_include")

	want := []parser.Constraint{
		{Name: "inc", Type: parser.Index, Columns: []string{"a"}, Method: "btree"},
		{Name: "u", Type: parser.Unique, Columns: []string{"c"}, Method: "btree"},
	}
	got := findTable(t, introspected, "e")
	sortConstraints(want)
	sortConstraints(got.Constraints)
	if diff := cmp.Diff(want, got.Constraints); diff != "" {
		t.Errorf("introspected e constraints mismatch (-want +got):\n%s", diff)
	}
	assertSchemaParity(t, "postgres", parsed, introspected)
}

func TestPostgresIntrospect_Partitioning(t *testing.T) {
	requireDatabases(t)
	ddl := `
CREATE SCHEMA pgi_parts;
CREATE TABLE pgi_parts.events (
	id bigint NOT NULL,
	created_at date NOT NULL,
	payload text,
	PRIMARY KEY (id, created_at)
) PARTITION BY RANGE (created_at);
CREATE TABLE pgi_parts.events_2024 PARTITION OF pgi_parts.events FOR VALUES FROM ('2024-01-01') TO ('2025-01-01');
CREATE TABLE pgi_parts.events_2025 PARTITION OF pgi_parts.events FOR VALUES FROM ('2025-01-01') TO ('2026-01-01')`
	parsed, introspected := pgParityCase(t, "DROP SCHEMA IF EXISTS pgi_parts CASCADE", ddl, "pgi_parts")

	for _, side := range []struct {
		name   string
		schema *parser.Schema
	}{{"parsed", parsed}, {"introspected", introspected}} {
		var tables []string
		for _, tbl := range side.schema.Tables {
			tables = append(tables, tbl.Schema+"."+tbl.Name)
		}
		if diff := cmp.Diff([]string{"pgi_parts.events"}, tables); diff != "" {
			t.Errorf("%s tables mismatch (-want +got):\n%s", side.name, diff)
		}
	}
	wantWarnings := []string{
		"CREATE TABLE events_2024 PARTITION OF events skipped in DDL file — the partitioned table is the entity",
		"CREATE TABLE events_2025 PARTITION OF events skipped in DDL file — the partitioned table is the entity",
	}
	if diff := cmp.Diff(wantWarnings, parsed.Warnings); diff != "" {
		t.Errorf("parser warnings mismatch (-want +got):\n%s", diff)
	}
	assertSchemaParity(t, "postgres", parsed, introspected, pgSkippedStatementExceptions...)
}

// A column with several foreign keys takes FKReference from the one whose
// name sorts first, under both sources, however the keys were declared.
func TestPostgresIntrospect_SameColumnForeignKeys(t *testing.T) {
	requireDatabases(t)
	const parent = "CREATE SCHEMA pgi_fks;\nCREATE TABLE pgi_fks.p (id int PRIMARY KEY, x int UNIQUE, y int UNIQUE);\n"
	x := &parser.FKReference{Table: "p", Schema: "pgi_fks", Column: "x"}
	y := &parser.FKReference{Table: "p", Schema: "pgi_fks", Column: "y"}
	tests := []struct {
		name    string
		ddl     string
		wantRef *parser.FKReference
	}{
		// PostgreSQL names them c_a_fkey and c_a_fkey1.
		{name: "two inline", ddl: "CREATE TABLE pgi_fks.c (a int REFERENCES pgi_fks.p(x) REFERENCES pgi_fks.p(y))", wantRef: x},
		{name: "named table level", ddl: "CREATE TABLE pgi_fks.c (a int, CONSTRAINT zz FOREIGN KEY (a) REFERENCES pgi_fks.p(x), CONSTRAINT aa FOREIGN KEY (a) REFERENCES pgi_fks.p(y))", wantRef: y},
		{name: "inline then named", ddl: "CREATE TABLE pgi_fks.c (a int REFERENCES pgi_fks.p(x), CONSTRAINT aa FOREIGN KEY (a) REFERENCES pgi_fks.p(y))", wantRef: y},
		{name: "added by alter", ddl: "CREATE TABLE pgi_fks.c (a int CONSTRAINT zz REFERENCES pgi_fks.p(x));\nALTER TABLE pgi_fks.c ADD CONSTRAINT aa FOREIGN KEY (a) REFERENCES pgi_fks.p(y)", wantRef: y},
		{name: "one dropped", ddl: "CREATE TABLE pgi_fks.c (a int, CONSTRAINT zz FOREIGN KEY (a) REFERENCES pgi_fks.p(x), CONSTRAINT aa FOREIGN KEY (a) REFERENCES pgi_fks.p(y));\nALTER TABLE pgi_fks.c DROP CONSTRAINT aa", wantRef: x},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			parsed, introspected := pgParityCase(t, "DROP SCHEMA IF EXISTS pgi_fks CASCADE", parent+tt.ddl, "pgi_fks")
			if diff := cmp.Diff(tt.wantRef, parser.ColumnByName(findTable(t, introspected, "c"), "a").FKReference); diff != "" {
				t.Errorf("c.a: introspected FKReference mismatch (-want +got):\n%s", diff)
			}
			assertSchemaParity(t, "postgres", parsed, introspected)
		})
	}
}
