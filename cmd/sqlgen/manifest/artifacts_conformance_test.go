// TestRunStage_DemarkedBreadcrumbsSurviveDisable pins PRD §30.3: "User deletes
// the marker line from a sqlgen-authored file → the file becomes user-owned on
// the next run (both overwrite and stale-delete are suppressed)", and "user-owned
// or user-adopted breadcrumbs are never deleted". Both models breadcrumbs are
// adopted after an enabled run; a second enabled run leaves them, and the flip
// to disabled removes the manifest directory but not them.
func TestRunStage_DemarkedBreadcrumbsSurviveDisable(t *testing.T) {
	dir := t.TempDir()
	cfg := stageConfig(dir, config.JSONLayoutSingle)
	runStage(t, makeStageInput(t, stageSchema(), cfg, pinnedTimestamp))

	adopted := map[string][]byte{}
	for _, f := range []string{"CLAUDE.md", "AGENTS.md"} {
		adopted[f] = stripFirstLine(t, filepath.Join(dir, f))
	}

	runStage(t, makeStageInput(t, stageSchema(), cfg, pinnedTimestamp))
	for f, body := range adopted {
		if got := readFile(t, filepath.Join(dir, f)); !bytes.Equal(got, body) {
			t.Errorf("enabled run rewrote the adopted %s; got:\n%s", f, got)
		}
	}

	cfg.Generation.Manifest.Enabled = new(false)
	runStage(t, makeStageInput(t, stageSchema(), cfg, pinnedTimestamp))
	assertAbsent(t, filepath.Join(dir, "manifest"))
	for f, body := range adopted {
		if got := readFile(t, filepath.Join(dir, f)); !bytes.Equal(got, body) {
			t.Errorf("disable removed or changed the adopted %s; got:\n%s", f, got)
		}
	}
}

// TestRunStage_UnmarkedBreadcrumbsNeverWrittenOrDeleted pins PRD §30.3: "File
// present, marker absent → user-owned: sqlgen never writes or deletes it", which
// "applies identically to the layered-mode graph/CLAUDE.md / graph/AGENTS.md
// breadcrumbs". Each file is planted before an enabled run (which warns about it
// and leaves it) and survives the flip to disabled.
func TestRunStage_UnmarkedBreadcrumbsNeverWrittenOrDeleted(t *testing.T) {
	tests := []struct {
		name string
		rel  string
		// marked is a sibling breadcrumb sqlgen does own, the control that the
		// enabled and disabled runs really write and sweep that directory.
		marked string
	}{
		{name: "models AGENTS.md", rel: "AGENTS.md", marked: "CLAUDE.md"},
		{name: "graph CLAUDE.md", rel: filepath.Join("graph", "CLAUDE.md"), marked: filepath.Join("graph", "AGENTS.md")},
		{name: "graph AGENTS.md", rel: filepath.Join("graph", "AGENTS.md"), marked: filepath.Join("graph", "CLAUDE.md")},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			cfg := stageConfig(dir, config.JSONLayoutSingle)
			cfg.API = graphQLAPIConfig(dir)
			target := filepath.Join(dir, tt.rel)
			body := "# hand-written notes\n"
			plantFile(t, target, body)

			warnings := runStage(t, makeStageInput(t, stageSchema(), cfg, pinnedTimestamp))
			if got := string(readFile(t, target)); got != body {
				t.Errorf("enabled run wrote the unmarked %s; got:\n%s", tt.rel, got)
			}
			if !slices.ContainsFunc(warnings, func(w string) bool { return strings.Contains(w, tt.rel) }) {
				t.Errorf("no warning names the user-owned %s; warnings = %v", tt.rel, warnings)
			}
			if !bytes.Contains(readFile(t, filepath.Join(dir, tt.marked)), []byte("Generated by sqlgen")) {
				t.Fatalf("fixture: sibling %s was not written with the marker", tt.marked)
			}

			cfg.Generation.Manifest.Enabled = new(false)
			runStage(t, makeStageInput(t, stageSchema(), cfg, pinnedTimestamp))
			if got := string(readFile(t, target)); got != body {
				t.Errorf("disable removed or changed the unmarked %s; got:\n%s", tt.rel, got)
			}
			assertAbsent(t, filepath.Join(dir, tt.marked))
		})
	}
}

