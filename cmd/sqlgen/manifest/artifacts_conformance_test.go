// TestRunStage_ColumnsKeepDeclarationOrder pins PRD §30.3: "columns[] keeps the
// table's declaration order". The fixture declares its columns out of
// lexicographic order so a sort would show.
func TestRunStage_ColumnsKeepDeclarationOrder(t *testing.T) {
	declared := []string{"id", "zeta", "alpha", "mid"}
	cols := make([]parser.Column, 0, len(declared))
	for _, name := range declared {
		cols = append(cols, parser.Column{Name: name, Type: "text", PrimaryKey: name == "id"})
	}
	if slices.IsSorted(declared) {
		t.Fatal("fixture: declared columns are already sorted")
	}
	schema := &parser.Schema{Tables: []parser.Table{{Name: "widgets", Columns: cols}}}

	dir := t.TempDir()
	runStage(t, makeStageInput(t, schema, stageConfig(dir, config.JSONLayoutSingle), pinnedTimestamp))

	entities := jsonObjects(t, decodeJSONFile(t, filepath.Join(dir, "manifest", "manifest_gen.json")), "entities")
	if len(entities) != 1 {
		t.Fatalf("got %d entities, want 1", len(entities))
	}
	got := jsonStrings(jsonObjects(t, entities[0], "columns"), "name")
	if diff := cmp.Diff(declared, got); diff != "" {
		t.Errorf("columns[] order (-declared +emitted):\n%s", diff)
	}
}

// TestEmitJSON_KeyedCollectionsSorted pins PRD §30.3: "every other collection is
// sorted lexicographically by stable key", for the keyed collections whose
// members are named things: entities, enums, and per entity its indexes,
// relationships, sort fields and filter column fields (the trailing And / Or
// combinators are not column fields and are excluded), and extras, which merge
// composite types, domain types and config extras into one list. Every input
// is fed in reverse lexicographic order so the sort is what puts them in
// order; the config extras arrive through a map, so their names are reversed
// too.
func TestEmitJSON_KeyedCollectionsSorted(t *testing.T) {
	cfg := baseConfig()
	cfg.Extras["Yolk"] = config.ExtraType{Fields: map[string]config.ExtraTypeField{"Size": {Type: "int"}}}
	cfg.Extras["Bead"] = config.ExtraType{Fields: map[string]config.ExtraTypeField{"Color": {Type: "string"}}}
	cfg.Tables["zoos"] = config.TableConfig{Relationships: []config.TableRelationship{
		{Name: "Zebras", Type: "one_to_many", Table: "animals", FK: "zoo_id"},
		{Name: "Antelopes", Type: "one_to_many", Table: "animals", FK: "home_zoo_id"},
	}}
	schema := &parser.Schema{
		Enums: []parser.Enum{
			{Name: "zoo_kind", Values: []string{"open", "closed"}},
			{Name: "animal_kind", Values: []string{"mammal", "bird"}},
		},
		CompositeTypes: []parser.CompositeType{
			{Name: "zone_box", Attributes: []parser.Attribute{{Name: "w", Type: "integer"}}},
			{Name: "crate_box", Attributes: []parser.Attribute{{Name: "h", Type: "integer"}}},
		},
		DomainTypes: []parser.DomainType{
			{Name: "x_code", BaseType: "text"},
			{Name: "a_code", BaseType: "text"},
		},
		Tables: []parser.Table{
			{
				Name: "zoos",
				Columns: []parser.Column{
					{Name: "id", Type: "uuid", PrimaryKey: true},
					{Name: "zcode", Type: "text"},
					{Name: "acode", Type: "text"},
				},
				Constraints: []parser.Constraint{
					{Name: "zoos_zcode_key", Type: parser.Unique, Columns: []string{"zcode"}},
					{Name: "zoos_acode_key", Type: parser.Unique, Columns: []string{"acode"}},
				},
			},
			{
				Name: "animals",
				Columns: []parser.Column{
					{Name: "id", Type: "uuid", PrimaryKey: true},
					{Name: "zoo_id", Type: "uuid"},
					{Name: "home_zoo_id", Type: "uuid"},
				},
			},
		},
	}
	doc, err := manifest.Build(testBuildInput(t, schema, cfg))
	if err != nil {
		t.Fatalf("Build: %v", err)
	}
	dir := t.TempDir()
	if err := manifest.EmitJSON(doc, fullManifestConfig(config.JSONLayoutSingle), dir); err != nil {
		t.Fatalf("EmitJSON: %v", err)
	}
	top := decodeJSONFile(t, filepath.Join(dir, "manifest", "manifest_gen.json"))

	check := func(what string, keys []string, wantLen int) {
		t.Helper()
		if len(keys) != wantLen {
			t.Errorf("%s = %v, want %d members (fixture drifted)", what, keys, wantLen)
		}
		if !slices.IsSorted(keys) {
			t.Errorf("%s not sorted: %v", what, keys)
		}
	}
	check("entities[].name", jsonStrings(jsonObjects(t, top, "entities"), "name"), 2)
	check("enums[].name", jsonStrings(jsonObjects(t, top, "enums"), "name"), 2)
	check("extras[].name", jsonStrings(jsonObjects(t, top, "extras"), "name"), 6)

	found := false
	for _, e := range jsonObjects(t, top, "entities") {
		if e["name"] != "Zoo" {
			continue
		}
		found = true
		check("Zoo indexes[].name", jsonStrings(jsonObjects(t, e, "indexes"), "name"), 3)
		check("Zoo relationships[].name", jsonStrings(jsonObjects(t, e, "relationships"), "name"), 2)
		sortObj, _ := e["sort"].(map[string]any)
		rawSort, _ := sortObj["fields"].([]any)
		sortFields := make([]string, 0, len(rawSort))
		for _, f := range rawSort {
			sortFields = append(sortFields, f.(string))
		}
		check("Zoo sort.fields", sortFields, 3)
		filterObj, _ := e["filter"].(map[string]any)
		fields := jsonStrings(jsonObjects(t, filterObj, "fields"), "name")
		columnFields := slices.DeleteFunc(slices.Clone(fields), func(n string) bool { return n == "And" || n == "Or" })
		check("Zoo filter.fields (column fields)", columnFields, 3)
	}
	if !found {
		t.Fatal("fixture: no Zoo entity in the emitted manifest")
	}
}

// TestRunStage_MarkdownFormatDroppedRemovesEveryMarkdownFile pins the "every"
// in PRD §30.3's format-drop rule: "markdown: every .md file in the owned
// markdown_dir, _index.md, _conventions.md and the per-entity files among
// them". A .md that is none of those — here an extra file beside a manifest a
// prior run wrote — goes too, while the JSON the current run emits stays.
func TestRunStage_MarkdownFormatDroppedRemovesEveryMarkdownFile(t *testing.T) {
	dir := t.TempDir()
	cfg := stageConfig(dir, config.JSONLayoutSingle)
	md := filepath.Join(dir, "manifest")

	runStage(t, makeStageInput(t, stageSchema(), cfg, pinnedTimestamp))
	extra := filepath.Join(md, "retired_entity.md")
	plantFile(t, extra, "# left over\n")

	cfg.Generation.Manifest.Formats = []string{config.ManifestFormatJSON}
	runStage(t, makeStageInput(t, stageSchema(), cfg, pinnedTimestamp))

	mds, err := filepath.Glob(filepath.Join(md, "*.md"))
	if err != nil {
		t.Fatalf("glob: %v", err)
	}
	if len(mds) != 0 {
		t.Errorf("markdown left in the owned markdown_dir after dropping the format: %v", mds)
	}
	assertExists(t, filepath.Join(md, "manifest_gen.json"))
}
