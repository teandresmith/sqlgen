// TestRunStage_FormatAndEmbedGates pins the §30.3 gates on a fresh output dir:
// manifest_gen.json and per-entity JSON need json in formats (even under
// per_entity), _index.md / _conventions.md / per-entity markdown need markdown,
// and manifest_embed_gen.go needs embed_in_client. Each case also checks the
// artifact its gate leaves on, so an empty run cannot pass.
func TestRunStage_FormatAndEmbedGates(t *testing.T) {
	tests := []struct {
		name    string
		layout  config.JSONLayout
		formats []string
		embed   bool
		absent  []string
		present []string
	}{
		{
			name:    "markdown only, per_entity layout",
			layout:  config.JSONLayoutPerEntity,
			formats: []string{config.ManifestFormatMarkdown},
			absent:  []string{"manifest/manifest_gen.json", "manifest/entities"},
			present: []string{"manifest/_index.md", "manifest/_conventions.md", "manifest/product.md"},
		},
		{
			name:    "json only, single layout",
			layout:  config.JSONLayoutSingle,
			formats: []string{config.ManifestFormatJSON},
			embed:   true,
			absent:  []string{"manifest/_index.md", "manifest/_conventions.md", "manifest/product.md", "manifest/audit_log.md"},
			present: []string{"manifest/manifest_gen.json", "manifest_embed_gen.go"},
		},
		{
			name:    "json only, per_entity layout",
			layout:  config.JSONLayoutPerEntity,
			formats: []string{config.ManifestFormatJSON},
			embed:   true,
			absent:  []string{"manifest/_index.md", "manifest/_conventions.md", "manifest/product.md", "manifest/audit_log.md"},
			present: []string{"manifest/manifest_gen.json", "manifest/entities/product.json"},
		},
		{
			name:    "embed_in_client false",
			layout:  config.JSONLayoutSingle,
			formats: []string{config.ManifestFormatJSON, config.ManifestFormatMarkdown},
			absent:  []string{"manifest_embed_gen.go"},
			present: []string{"manifest/manifest_gen.json", "manifest/_index.md"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			cfg := stageConfig(dir, tt.layout)
			cfg.Generation.Manifest.Formats = tt.formats
			cfg.Generation.Manifest.EmbedInClient = new(tt.embed)

			runStage(t, makeStageInput(t, stageSchema(), cfg, pinnedTimestamp))

			for _, f := range tt.absent {
				assertAbsent(t, filepath.Join(dir, filepath.FromSlash(f)))
			}
			for _, f := range tt.present {
				assertExists(t, filepath.Join(dir, filepath.FromSlash(f)))
			}
			if !slices.Contains(tt.formats, config.ManifestFormatJSON) {
				jsons, err := filepath.Glob(filepath.Join(dir, "manifest", "*.json"))
				if err != nil {
					t.Fatalf("glob: %v", err)
				}
				if len(jsons) != 0 {
					t.Errorf("markdown-only run wrote JSON: %v", jsons)
				}
			}
			if !slices.Contains(tt.formats, config.ManifestFormatMarkdown) {
				mds, err := filepath.Glob(filepath.Join(dir, "manifest", "*.md"))
				if err != nil {
					t.Fatalf("glob: %v", err)
				}
				if len(mds) != 0 {
					t.Errorf("json-only run wrote markdown: %v", mds)
				}
			}
		})
	}
}

