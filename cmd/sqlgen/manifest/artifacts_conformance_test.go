// TestRunStage_IncludeExamplesFalseStripsEntityExamples pins PRD §30.2: "When
// false, per-entity examples arrays are stripped" — read from the emitted
// entity records in both layouts, with the default run as the control that the
// key would otherwise be there.
func TestRunStage_IncludeExamplesFalseStripsEntityExamples(t *testing.T) {
	tests := []struct {
		name            string
		layout          config.JSONLayout
		includeExamples bool
	}{
		{name: "single layout, default keeps examples", layout: config.JSONLayoutSingle, includeExamples: true},
		{name: "single layout, false strips examples", layout: config.JSONLayoutSingle, includeExamples: false},
		{name: "per_entity layout, default keeps examples", layout: config.JSONLayoutPerEntity, includeExamples: true},
		{name: "per_entity layout, false strips examples", layout: config.JSONLayoutPerEntity, includeExamples: false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			cfg := stageConfig(dir, tt.layout)
			if !tt.includeExamples {
				cfg.Generation.Manifest.IncludeExamples = new(false)
			}
			runStage(t, makeStageInput(t, stageSchema(), cfg, pinnedTimestamp))

			md := filepath.Join(dir, "manifest")
			var records []map[string]any
			if tt.layout == config.JSONLayoutSingle {
				records = jsonObjects(t, decodeJSONFile(t, filepath.Join(md, "manifest_gen.json")), "entities")
			} else {
				for _, f := range []string{"product.json", "audit_log.json"} {
					records = append(records, decodeJSONFile(t, filepath.Join(md, "entities", f)))
				}
			}
			if len(records) != 2 {
				t.Fatalf("got %d entity records, want 2", len(records))
			}
			for _, r := range records {
				ex, has := r["examples"]
				if has != tt.includeExamples {
					t.Errorf("entity %v: examples present = %v (value %v), want %v", r["table"], has, ex, tt.includeExamples)
				}
			}
		})
	}
}

// TestRunStage_IncludeExamplesFalseKeepsConventionsExamples pins PRD §30.2:
// "Conventions examples in _conventions.md are always retained." The file
// carries its Examples block with include_examples: false, byte-identical to the
// default run.
func TestRunStage_IncludeExamplesFalseKeepsConventionsExamples(t *testing.T) {
	render := func(include bool) []byte {
		dir := t.TempDir()
		cfg := stageConfig(dir, config.JSONLayoutSingle)
		cfg.Generation.Manifest.IncludeExamples = new(include)
		runStage(t, makeStageInput(t, stageSchema(), cfg, pinnedTimestamp))
		return readFile(t, filepath.Join(dir, "manifest", "_conventions.md"))
	}

	stripped := render(false)
	if !bytes.Contains(stripped, []byte("\nExamples:\n- `")) {
		t.Errorf("_conventions.md lost its Examples block under include_examples: false; got:\n%s", stripped)
	}
	if kept := render(true); !bytes.Equal(stripped, kept) {
		t.Errorf("_conventions.md differs between include_examples false and true:\n%s", cmp.Diff(string(kept), string(stripped)))
	}
}

// TestRunStage_TableOptOutLeavesEmittedEntities pins PRD §30.2's per-table
// opt-out: "suppresses the table from entities[] in the JSON ... and excludes
// it from the ManifestEntity() lookup". In both layouts the top-level
// entities[] lists only the kept table, and the emitted files, loaded through
// the runtime manifest.LoadInto the generated package calls, answer the lookup
// for the kept table and ErrEntityNotFound for the opted-out one.
func TestRunStage_TableOptOutLeavesEmittedEntities(t *testing.T) {
	tests := []struct {
		name   string
		layout config.JSONLayout
	}{
		{name: "single layout", layout: config.JSONLayoutSingle},
		{name: "per_entity layout", layout: config.JSONLayoutPerEntity},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			cfg := stageConfig(dir, tt.layout)
			cfg.Tables["audit_logs"] = config.TableConfig{Manifest: &config.TableManifestConfig{Enabled: new(false)}}

			runStage(t, makeStageInput(t, stageSchema(), cfg, pinnedTimestamp))

			md := filepath.Join(dir, "manifest")
			index := jsonObjects(t, decodeJSONFile(t, filepath.Join(md, "manifest_gen.json")), "entities")
			if got, want := jsonStrings(index, "table"), []string{"products"}; !cmp.Equal(got, want) {
				t.Errorf("manifest_gen.json entities[] tables = %v, want %v", got, want)
			}
			lookup := loadEmittedLookup(t, md, tt.layout)
			if e, err := lookup("products"); err != nil || e.Table != "products" {
				t.Errorf("ManifestEntity(%q) = %v, %v; want the products record", "products", e, err)
			}
			if _, err := lookup("audit_logs"); !errors.Is(err, rtmanifest.ErrEntityNotFound) {
				t.Errorf("ManifestEntity(%q) error = %v, want manifest.ErrEntityNotFound for an opted-out table", "audit_logs", err)
			}
		})
	}
}

