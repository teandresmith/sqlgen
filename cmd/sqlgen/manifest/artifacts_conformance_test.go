// Conformance fill for PRD §30.2 (configuration) and §30.3 (generated
// artifacts). Every test drives the real RunStage (or Build → EmitJSON) and
// reads what lands on disk, so the assertions are about the emitted artifacts
// rather than the builder's Go structs.

const pinnedTimestamp = "2026-07-09T00:00:00Z"

// decodeJSONFile decodes a JSON artifact into a generic map so a test asserts the
// emitted keys, not the Go struct that produced them.
func decodeJSONFile(t *testing.T, path string) map[string]any {
	t.Helper()
	var out map[string]any
	if err := json.Unmarshal(readFile(t, path), &out); err != nil {
		t.Fatalf("decoding %s: %v", path, err)
	}
	return out
}

// jsonObjects returns the JSON array at key as a slice of objects.
func jsonObjects(t *testing.T, doc map[string]any, key string) []map[string]any {
	t.Helper()
	raw, ok := doc[key].([]any)
	if !ok {
		t.Fatalf("key %q is %T, want a JSON array", key, doc[key])
	}
	out := make([]map[string]any, 0, len(raw))
	for i, v := range raw {
		obj, ok := v.(map[string]any)
		if !ok {
			t.Fatalf("%s[%d] is %T, want a JSON object", key, i, v)
		}
		out = append(out, obj)
	}
	return out
}

// jsonStrings returns the value of key on every object in objs.
func jsonStrings(objs []map[string]any, key string) []string {
	out := make([]string, 0, len(objs))
	for _, o := range objs {
		s, _ := o[key].(string)
		out = append(out, s)
	}
	return out
}

// loadEmittedLookup loads the emitted manifest the way the generated package's
// init() does (manifest_embed.go.tmpl): runtime manifest.LoadInto over the
// top-level JSON, with the per-entity directory as the entity FS under
// per_entity and nil under single. It returns a lookup with the body of the
// generated Client.ManifestEntity, so a test asserts what the generated
// lookup answers for the files on disk.
func loadEmittedLookup(t *testing.T, mdDir string, layout config.JSONLayout) func(table string) (*rtmanifest.Entity, error) {
	t.Helper()
	top := readFile(t, filepath.Join(mdDir, "manifest_gen.json"))
	var entityFS fs.FS
	if layout == config.JSONLayoutPerEntity {
		entityFS = os.DirFS(filepath.Join(mdDir, "entities"))
	}
	var doc rtmanifest.Document
	entities := map[string]*rtmanifest.Entity{}
	if err := rtmanifest.LoadInto(top, entityFS, &doc, entities); err != nil {
		t.Fatalf("manifest.LoadInto: %v", err)
	}
	return func(table string) (*rtmanifest.Entity, error) {
		return rtmanifest.FindEntity(entities, table)
	}
}

// stripFirstLine removes the first line of path, the way a consumer adopts a
// sqlgen breadcrumb by deleting the provenance marker line.
func stripFirstLine(t *testing.T, path string) []byte {
	t.Helper()
	_, rest, found := bytes.Cut(readFile(t, path), []byte("\n"))
	if !found {
		t.Fatalf("%s has no newline", path)
	}
	if bytes.Contains(rest, []byte("Generated by sqlgen")) {
		t.Fatalf("fixture: %s still carries the marker after stripping its first line", path)
	}
	if err := os.WriteFile(path, rest, 0o600); err != nil {
		t.Fatalf("rewriting %s: %v", path, err)
	}
	return rest
}

