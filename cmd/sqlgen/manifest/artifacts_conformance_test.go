// TestRunStage_CustomJSONFilenameInPerEntityLayout pins PRD §30.2: json_filename
// is "Used in both layouts (in per_entity it carries the index)". A custom name
// under per_entity is the file the index lands in, and the default name is not
// written beside it.
func TestRunStage_CustomJSONFilenameInPerEntityLayout(t *testing.T) {
	dir := t.TempDir()
	cfg := stageConfig(dir, config.JSONLayoutPerEntity)
	cfg.Generation.Manifest.JSONFilename = "surface.json"

	runStage(t, makeStageInput(t, stageSchema(), cfg, pinnedTimestamp))

	md := filepath.Join(dir, "manifest")
	assertAbsent(t, filepath.Join(md, "manifest_gen.json"))
	index := decodeJSONFile(t, filepath.Join(md, "surface.json"))
	if gen, _ := index["generator"].(map[string]any); gen["name"] != "sqlgen" {
		t.Errorf("surface.json generator = %v, want name sqlgen", index["generator"])
	}
	if got, want := jsonStrings(jsonObjects(t, index, "entities"), "table"), []string{"audit_logs", "products"}; !cmp.Equal(got, want) {
		t.Errorf("surface.json index entities = %v, want %v", got, want)
	}
	assertExists(t, filepath.Join(md, "entities", "product.json"))
	assertExists(t, filepath.Join(md, "entities", "audit_log.json"))
}

