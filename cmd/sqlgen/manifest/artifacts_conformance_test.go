// TestRunStage_ConventionsMDFollowsDirOwnership pins PRD §30.3's directory
// ownership rule for _conventions.md: a manifest dir with no anchor (no
// sqlgen _index.md, no sqlgen json_filename artifact) is left whole, its
// _conventions.md included; one a prior enabled run wrote loses it along with
// the directory.
func TestRunStage_ConventionsMDFollowsDirOwnership(t *testing.T) {
	t.Run("no anchor leaves _conventions.md", func(t *testing.T) {
		dir := t.TempDir()
		md := filepath.Join(dir, "manifest")
		seedDir(t, md, map[string]string{
			"_conventions.md": "# conventions we wrote by hand\n",
			"notes.md":        "# notes\n",
		})
		cfg := baseConfig()
		cfg.Output.Dir = dir
		cfg.Generation.Manifest = &config.ManifestConfig{Enabled: new(false)}

		res := runStageResult(t, makeStageInput(t, stageSchema(), cfg, pinnedTimestamp))

		assertExists(t, filepath.Join(md, "_conventions.md"))
		assertExists(t, filepath.Join(md, "notes.md"))
		if len(res.Deleted) != 0 {
			t.Errorf("deleted %v from an unanchored manifest dir", res.Deleted)
		}
	})

	t.Run("anchored dir takes _conventions.md with it", func(t *testing.T) {
		dir := t.TempDir()
		cfg := stageConfig(dir, config.JSONLayoutSingle)
		conventions := filepath.Join(dir, "manifest", "_conventions.md")
		runStage(t, makeStageInput(t, stageSchema(), cfg, pinnedTimestamp))
		if !exists(t, conventions) {
			t.Fatal("fixture: enabled run did not write _conventions.md")
		}

		cfg.Generation.Manifest.Enabled = new(false)
		runStage(t, makeStageInput(t, stageSchema(), cfg, pinnedTimestamp))

		assertAbsent(t, conventions)
		assertAbsent(t, filepath.Join(dir, "manifest"))
	})
}

