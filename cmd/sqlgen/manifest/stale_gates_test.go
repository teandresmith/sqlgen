// TestRunStage_MarkdownFormatDroppedRemovesMarkdown pins PRD §30.3: "All
// manifest artifacts participate in stale-file cleanup." A run with formats
// [json, markdown] followed by one with formats [json] — the manifest still
// enabled — must not leave the previous run's markdown behind: _index.md,
// _conventions.md and every per-entity .md are no longer artifacts of the
// current configuration. The JSON the current run emits stays.
func TestRunStage_MarkdownFormatDroppedRemovesMarkdown(t *testing.T) {
	dir := t.TempDir()
	cfg := stageConfig(dir, config.JSONLayoutSingle)
	md := filepath.Join(dir, "manifest")

	runStage(t, makeStageInput(t, stageSchema(), cfg, "2026-07-09T00:00:00Z"))
	for _, f := range []string{"_index.md", "_conventions.md", "product.md", "audit_log.md"} {
		if !exists(t, filepath.Join(md, f)) {
			t.Fatalf("fixture: first run did not write %s", f)
		}
	}

	cfg.Generation.Manifest.Formats = []string{config.ManifestFormatJSON}
	runStage(t, makeStageInput(t, stageSchema(), cfg, "2026-07-09T00:00:00Z"))

	assertExists(t, filepath.Join(md, "manifest_gen.json"))
	assertAbsent(t, filepath.Join(md, "_index.md"))
	assertAbsent(t, filepath.Join(md, "_conventions.md"))
	assertAbsent(t, filepath.Join(md, "product.md"))
	assertAbsent(t, filepath.Join(md, "audit_log.md"))
}

// TestRunStage_GraphQLDisabledRemovesGraphBreadcrumbs pins PRD §30.3: the graph
// package receives its breadcrumbs "when GraphQL is enabled", and "all
// manifest artifacts participate in stale-file cleanup". Disabling GraphQL
// while the manifest stays enabled must therefore remove the sqlgen-marked
// graph/CLAUDE.md and graph/AGENTS.md the earlier run wrote. The models
// breadcrumbs, still gated on, stay.
func TestRunStage_GraphQLDisabledRemovesGraphBreadcrumbs(t *testing.T) {
	dir := t.TempDir()
	cfg := stageConfig(dir, config.JSONLayoutSingle)
	graphDir := filepath.Join(dir, "graph")
	cfg.API = &config.APIConfig{
		Enabled: true,
		GraphQL: &config.GraphQLAPIConfig{
			Enabled:     true,
			SchemaDir:   graphDir,
			ResolverDir: graphDir,
			Package:     "graph",
		},
	}

	runStage(t, makeStageInput(t, stageSchema(), cfg, "2026-07-09T00:00:00Z"))
	for _, f := range []string{"CLAUDE.md", "AGENTS.md"} {
		got := readFile(t, filepath.Join(graphDir, f))
		if !bytes.Contains(got, []byte("Generated by sqlgen")) {
			t.Fatalf("fixture: graph/%s missing the provenance marker; got:\n%s", f, got)
		}
	}

	cfg.API.GraphQL.Enabled = false
	runStage(t, makeStageInput(t, stageSchema(), cfg, "2026-07-09T00:00:00Z"))

	assertAbsent(t, filepath.Join(graphDir, "CLAUDE.md"))
	assertAbsent(t, filepath.Join(graphDir, "AGENTS.md"))
	assertExists(t, filepath.Join(dir, "CLAUDE.md"))
	assertExists(t, filepath.Join(dir, "AGENTS.md"))
}

// TestRunStage_JSONFormatDroppedRemovesJSON is the reverse flip: a run with
// formats [json, markdown] under the per_entity layout followed by one with
// formats [markdown] removes the top-level manifest JSON and every per-entity
// JSON file (then the emptied entities directory). The markdown the current
// run emits stays.
func TestRunStage_JSONFormatDroppedRemovesJSON(t *testing.T) {
	dir := t.TempDir()
	cfg := stageConfig(dir, config.JSONLayoutPerEntity)
	md := filepath.Join(dir, "manifest")
	entities := filepath.Join(md, "entities")

	runStage(t, makeStageInput(t, stageSchema(), cfg, "2026-07-09T00:00:00Z"))
	for _, f := range []string{filepath.Join(md, "manifest_gen.json"), filepath.Join(entities, "product.json"), filepath.Join(entities, "audit_log.json")} {
		if !exists(t, f) {
			t.Fatalf("fixture: first run did not write %s", f)
		}
	}

	cfg.Generation.Manifest.Formats = []string{config.ManifestFormatMarkdown}
	cfg.Generation.Manifest.EmbedInClient = new(false)
	runStage(t, makeStageInput(t, stageSchema(), cfg, "2026-07-09T00:00:00Z"))

	assertExists(t, filepath.Join(md, "_index.md"))
	assertExists(t, filepath.Join(md, "product.md"))
	assertAbsent(t, filepath.Join(md, "manifest_gen.json"))
	assertAbsent(t, filepath.Join(entities, "product.json"))
	assertAbsent(t, filepath.Join(entities, "audit_log.json"))
	assertAbsent(t, entities)
}

// TestRunStage_MarkdownFormatDroppedLeavesUnanchoredDir guards the ownership
// rule on a formats flip: a markdown_dir holding markdown but no sqlgen-marked
// _index.md was never shown to be sqlgen's markdown, so a [json] run leaves
// every .md in it alone — even though that run writes its own JSON there.
func TestRunStage_MarkdownFormatDroppedLeavesUnanchoredDir(t *testing.T) {
	dir := t.TempDir()
	cfg := stageConfig(dir, config.JSONLayoutSingle)
	cfg.Generation.Manifest.Formats = []string{config.ManifestFormatJSON}
	md := filepath.Join(dir, "manifest")
	if err := os.MkdirAll(md, 0o750); err != nil {
		t.Fatalf("creating markdown dir: %v", err)
	}
	userFiles := []string{"_index.md", "notes.md", "product.md"}
	for _, f := range userFiles {
		if err := os.WriteFile(filepath.Join(md, f), []byte("# hand-written\n"), 0o600); err != nil {
			t.Fatalf("writing %s: %v", f, err)
		}
	}

	runStage(t, makeStageInput(t, stageSchema(), cfg, "2026-07-09T00:00:00Z"))

	assertExists(t, filepath.Join(md, "manifest_gen.json"))
	for _, f := range userFiles {
		assertExists(t, filepath.Join(md, f))
	}
}

// TestRunStage_GraphQLDisabledLeavesUnmarkedGraphBreadcrumbs guards the
// ownership rule on a GraphQL disable: a graph/CLAUDE.md without the provenance
// marker is the consumer's and survives, while the marked AGENTS.md beside it
// is removed. GraphQL is disabled with the api block kept, so the resolver dir
// still names the graph package.
func TestRunStage_GraphQLDisabledLeavesUnmarkedGraphBreadcrumbs(t *testing.T) {
	dir := t.TempDir()
	cfg := stageConfig(dir, config.JSONLayoutSingle)
	graphDir := filepath.Join(dir, "graph")
	cfg.API = &config.APIConfig{
		Enabled: true,
		GraphQL: &config.GraphQLAPIConfig{Enabled: true, SchemaDir: graphDir, ResolverDir: graphDir, Package: "graph"},
	}
	runStage(t, makeStageInput(t, stageSchema(), cfg, "2026-07-09T00:00:00Z"))

	userBody := []byte("# my graph notes\n")
	if err := os.WriteFile(filepath.Join(graphDir, "CLAUDE.md"), userBody, 0o600); err != nil {
		t.Fatalf("adopting graph/CLAUDE.md: %v", err)
	}

	cfg.API.GraphQL.Enabled = false
	runStage(t, makeStageInput(t, stageSchema(), cfg, "2026-07-09T00:00:00Z"))

	if got := readFile(t, filepath.Join(graphDir, "CLAUDE.md")); !bytes.Equal(got, userBody) {
		t.Errorf("unmarked graph/CLAUDE.md changed; got:\n%s", got)
	}
	assertAbsent(t, filepath.Join(graphDir, "AGENTS.md"))
}

// TestRunStage_NoAPIBlockLeavesGraphBreadcrumbs pins that graph breadcrumb
// cleanup only looks in a configured graph package: with no api block the
// config names no resolver dir, so a sqlgen-marked <output.dir>/graph/CLAUDE.md
// is not swept — the default dir is not guessed.
func TestRunStage_NoAPIBlockLeavesGraphBreadcrumbs(t *testing.T) {
	dir := t.TempDir()
	cfg := stageConfig(dir, config.JSONLayoutSingle)
	graphDir := filepath.Join(dir, "graph")
	if err := os.MkdirAll(graphDir, 0o750); err != nil {
		t.Fatalf("creating graph dir: %v", err)
	}
	marked := []byte("<!-- Generated by sqlgen — manifest breadcrumb. -->\n\n# GraphQL surface\n")
	target := filepath.Join(graphDir, "CLAUDE.md")
	if err := os.WriteFile(target, marked, 0o600); err != nil {
		t.Fatalf("writing graph/CLAUDE.md: %v", err)
	}

	res := runStageResult(t, makeStageInput(t, stageSchema(), cfg, "2026-07-09T00:00:00Z"))

	if got := readFile(t, target); !bytes.Equal(got, marked) {
		t.Errorf("graph/CLAUDE.md changed with no api block; got:\n%s", got)
	}
	for _, d := range res.Deleted {
		if strings.Contains(filepath.ToSlash(d), "graph/") {
			t.Errorf("deleted %s with no api block configured", d)
		}
	}
}
