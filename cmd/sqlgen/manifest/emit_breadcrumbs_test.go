// allBreadcrumbs enables every breadcrumb sub-flag (the resolved-config state
// when the manifest is enabled with no overrides).
func allBreadcrumbs() config.BreadcrumbsConfig {
	return config.BreadcrumbsConfig{
		ClaudeMD:   new(true),
		AgentsMD:   new(true),
		PackageDoc: new(true),
	}
}

func modelsInput(dir string, bc config.BreadcrumbsConfig) manifest.BreadcrumbsInput {
	return manifest.BreadcrumbsInput{
		Doc:         newFixtureDocument(),
		Breadcrumbs: bc,
		OutputDir:   dir,
		MarkdownDir: "manifest",
	}
}

// TestEmitBreadcrumbs_Goldens pins the models breadcrumb content and the
// byte-identity of CLAUDE.md / AGENTS.md (single template, two paths), including
// the leading provenance marker.
func TestEmitBreadcrumbs_Goldens(t *testing.T) {
	dir := t.TempDir()
	if _, err := manifest.EmitBreadcrumbs(modelsInput(dir, allBreadcrumbs())); err != nil {
		t.Fatalf("EmitBreadcrumbs error: %v", err)
	}

	claude := readFile(t, filepath.Join(dir, "CLAUDE.md"))
	agents := readFile(t, filepath.Join(dir, "AGENTS.md"))
	if !bytes.Equal(claude, agents) {
		t.Errorf("CLAUDE.md and AGENTS.md are not byte-identical")
	}
	if !bytes.HasPrefix(claude, []byte("<!-- Generated by sqlgen")) {
		t.Errorf("breadcrumb missing leading provenance marker; got:\n%s", claude)
	}
	checkGolden(t, filepath.Join("testdata", "golden", "breadcrumbs", "CLAUDE.md"), claude)
}

// TestEmitBreadcrumbs_LayeredGoldens pins the layered graph breadcrumb content
// (three-pointer layout) and its byte-identity across CLAUDE.md / AGENTS.md.
