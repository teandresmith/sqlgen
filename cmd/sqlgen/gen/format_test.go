func TestHeader(t *testing.T) {
	tests := []struct {
		name    string
		version string
		want    string
	}{
		{
			name:    "standard version",
			version: "v1.2.0",
			want:    "// Code generated by sqlgen v1.2.0. DO NOT EDIT.",
		},
		{
			name:    "dev version",
			version: "v0.0.0-dev",
			want:    "// Code generated by sqlgen v0.0.0-dev. DO NOT EDIT.",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := gen.Header(tt.version)
			if got != tt.want {
				t.Errorf("Header(%q) = %q, want %q", tt.version, got, tt.want)
			}
		})
	}
}

func TestFormat_validGoFile(t *testing.T) {
	raw := []byte(`package example

func Hello() string {
	return "hello"
}
`)
	version := "v1.0.0"

	got, err := gen.Format(raw, version, "example.go")
	if err != nil {
		t.Fatalf("Format() unexpected error: %v", err)
	}

	output := string(got)

	// Header is the first line.
	wantHeader := gen.Header(version)
	if !strings.HasPrefix(output, wantHeader) {
		firstLine := strings.SplitN(output, "\n", 2)[0]
		t.Errorf("Format() first line = %q, want %q", firstLine, wantHeader)
	}

	// Package declaration is present.
	if !strings.Contains(output, "package example") {
		t.Error("Format() output missing package declaration")
	}

	// Function is present.
	if !strings.Contains(output, "func Hello()") {
		t.Error("Format() output missing function")
	}
}

func TestFormat_addsImports(t *testing.T) {
	// Raw template output uses fmt.Println without importing fmt.
	// goimports should add the import.
	raw := []byte(`package example

func Hello() {
	fmt.Println("hello")
}
`)

	got, err := gen.Format(raw, "v1.0.0", "example.go")
	if err != nil {
		t.Fatalf("Format() unexpected error: %v", err)
	}

	if !strings.Contains(string(got), `"fmt"`) {
		t.Error("Format() output missing auto-added fmt import")
	}
}

func TestFormat_goimportsFailureIncludesRawOutput(t *testing.T) {
	// Invalid Go code that will cause goimports to fail.
	raw := []byte(`package example

func broken( {
`)
	_, err := gen.Format(raw, "v1.0.0", "broken.go")
	if err == nil {
		t.Fatal("Format() expected error for invalid Go, got nil")
	}

	errMsg := err.Error()

	if !strings.Contains(errMsg, "goimports failed") {
		t.Errorf("Format() error missing 'goimports failed': %s", errMsg)
	}

	if !strings.Contains(errMsg, "raw template output") {
		t.Errorf("Format() error missing raw template output: %s", errMsg)
	}

	if !strings.Contains(errMsg, "func broken(") {
		t.Errorf("Format() error missing actual template content: %s", errMsg)
	}
}

func TestFormat_headerIsFirstLine(t *testing.T) {
	raw := []byte("package example\n")
	version := "v2.0.0"

	got, err := gen.Format(raw, version, "example.go")
	if err != nil {
		t.Fatalf("Format() unexpected error: %v", err)
	}

	lines := strings.SplitN(string(got), "\n", 2)
	wantFirst := gen.Header(version)
	if lines[0] != wantFirst {
		t.Errorf("Format() first line = %q, want %q", lines[0], wantFirst)
	}
}

func TestExecuteAndWrite_createsDirectories(t *testing.T) {
	dir := t.TempDir()
	outPath := filepath.Join(dir, "nested", "deep", "output_gen.go")

	tmpl := template.Must(template.New("test").Parse(`package example

func Hello() string {
	return "hello"
}
`))

	err := gen.ExecuteAndWrite(tmpl, "test", nil, outPath, "v1.0.0")
	if err != nil {
		t.Fatalf("ExecuteAndWrite() unexpected error: %v", err)
	}

	// Verify the file exists.
	info, err := os.Stat(outPath)
	if err != nil {
		t.Fatalf("output file not found: %v", err)
	}

	// Verify the nested directories were created.
	nestedDir := filepath.Join(dir, "nested", "deep")
	if _, err := os.Stat(nestedDir); err != nil {
		t.Errorf("nested directory not created: %v", err)
	}

	// Verify content has the header.
	data, err := os.ReadFile(outPath) //nolint:gosec
	if err != nil {
		t.Fatalf("reading output: %v", err)
	}
	if !strings.HasPrefix(string(data), gen.Header("v1.0.0")) {
		t.Error("ExecuteAndWrite() output missing header")
	}

	// Verify file size is non-zero.
	if info.Size() == 0 {
		t.Error("ExecuteAndWrite() wrote empty file")
	}
}

func TestExecuteAndWrite_filePermissions(t *testing.T) {
	dir := t.TempDir()
	outPath := filepath.Join(dir, "perms_gen.go")

	tmpl := template.Must(template.New("test").Parse("package example\n"))

	if err := gen.ExecuteAndWrite(tmpl, "test", nil, outPath, "v1.0.0"); err != nil {
		t.Fatalf("ExecuteAndWrite() unexpected error: %v", err)
	}

	info, err := os.Stat(outPath)
	if err != nil {
		t.Fatalf("stat output: %v", err)
	}

	// On Unix, check that permissions are 0600.
	perm := info.Mode().Perm()
	if perm != 0o600 {
		t.Errorf("file permissions = %o, want %o", perm, 0o600)
	}
}

func TestExecuteAndWrite_templateError(t *testing.T) {
	// Template that references a missing field.
	tmpl := template.Must(template.New("bad").Parse("{{ .Missing }}"))

	dir := t.TempDir()
	outPath := filepath.Join(dir, "bad_gen.go")

	err := gen.ExecuteAndWrite(tmpl, "bad", struct{}{}, outPath, "v1.0.0")
	if err == nil {
		t.Fatal("ExecuteAndWrite() expected template error, got nil")
	}

	if !strings.Contains(err.Error(), "executing template") {
		t.Errorf("ExecuteAndWrite() error = %q, want containing 'executing template'", err.Error())
	}
}

func TestExecuteAndWrite_producesValidGoFile(t *testing.T) {
	dir := t.TempDir()
	outPath := filepath.Join(dir, "valid_gen.go")

	tmpl := template.Must(template.New("valid").Parse(`package example

import "context"

// Client provides database operations.
type Client struct {
	ctx context.Context
}
`))

	if err := gen.ExecuteAndWrite(tmpl, "valid", nil, outPath, "v1.0.0"); err != nil {
		t.Fatalf("ExecuteAndWrite() unexpected error: %v", err)
	}

	data, err := os.ReadFile(outPath) //nolint:gosec
	if err != nil {
		t.Fatalf("reading output: %v", err)
	}

	output := string(data)

	// Verify header.
	if !strings.HasPrefix(output, gen.Header("v1.0.0")) {
		t.Error("output missing header")
	}

	// Verify package declaration.
	if !strings.Contains(output, "package example") {
		t.Error("output missing package declaration")
	}

	// Verify import is preserved (used by the struct).
	if !strings.Contains(output, `"context"`) {
		t.Error("output missing context import")
	}
}
