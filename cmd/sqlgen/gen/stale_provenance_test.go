package gen_test

import (
	"os"
	"path/filepath"
	"slices"
	"testing"

	"github.com/teandresmith/sqlgen/cmd/sqlgen/gen"
)

// The stale sweep deleted any orphaned *_gen.go in output.dir
// on name alone. output.dir defaults to "." (PRD §4.2), so with
// layout: file_per_table the sweep runs over a consumer's module root — where
// wire_gen.go, mock_gen.go and stringer output are ordinary residents, all
// bearing the *_gen.go suffix and none of them sqlgen's.
//
// PRD §23.8 scopes the sweep to "orphaned *generated* files" and makes the
// suffix the filter on what is *considered*; the header is what proves
// authorship.

func TestStaleFiles_RequiresSqlgenProvenance(t *testing.T) {
	// Header text other tools actually emit, so the test fails if the check
	// ever loosens to Go's generic `// Code generated ... DO NOT EDIT.` form.
	const (
		sqlgenHeader = "// Code generated by sqlgen dev. DO NOT EDIT.\n\npackage models\n"
		wireHeader   = "// Code generated by Wire. DO NOT EDIT.\n\npackage models\n"
		mockHeader   = "// Code generated by MockGen. DO NOT EDIT.\n\npackage models\n"
		noHeader     = "package models\n\n// hand-written, named to look generated\n"
	)

	tests := []struct {
		name       string
		content    string
		wantStale  bool
		wantReason string
	}{
		{name: "sqlgen output is swept", content: sqlgenHeader, wantStale: true},
		{name: "wire output is left alone", content: wireHeader, wantReason: "another generator's file"},
		{name: "mockgen output is left alone", content: mockHeader, wantReason: "another generator's file"},
		{name: "unmarked file is left alone", content: noHeader, wantReason: "no provenance header"},
		{
			// Deleting the header disowns the file, mirroring the manifest
			// breadcrumb rule (PRD §30.3).
			name:       "header stripped from a prior sqlgen file disowns it",
			content:    "package models\n",
			wantReason: "header removed by the consumer",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			orphan := filepath.Join(dir, "orphan_gen.go")
			if err := os.WriteFile(orphan, []byte(tt.content), 0o600); err != nil {
				t.Fatalf("seeding %s: %v", orphan, err)
			}

			stale, err := gen.StaleFiles(dir, nil)
			if err != nil {
				t.Fatalf("StaleFiles() unexpected error: %v", err)
			}

			got := slices.Contains(stale, orphan)
			if got != tt.wantStale {
				t.Errorf("StaleFiles() considered orphan_gen.go stale = %v, want %v (%s)\nstale: %v",
					got, tt.wantStale, tt.wantReason, stale)
			}
		})
	}
}

// TestStaleFiles_WrittenFilesAreNeverStale pins the pre-existing contract the
// provenance check must not disturb: a file produced by this run is not stale,
// header or not.
func TestStaleFiles_WrittenFilesAreNeverStale(t *testing.T) {
	dir := t.TempDir()
	current := filepath.Join(dir, "user_gen.go")
	if err := os.WriteFile(current, []byte(gen.Header("dev")+"\n\npackage models\n"), 0o600); err != nil {
		t.Fatalf("seeding: %v", err)
	}

	stale, err := gen.StaleFiles(dir, []string{current})
	if err != nil {
		t.Fatalf("StaleFiles() unexpected error: %v", err)
	}
	if len(stale) != 0 {
		t.Errorf("StaleFiles() = %v, want empty — a file written this run is never stale", stale)
	}
}

// TestStaleFiles_NonGenSuffixUntouched pins PRD §23.8's other half: "Files that
// do not end in _gen.go are never touched", regardless of what header they
// carry.
func TestStaleFiles_NonGenSuffixUntouched(t *testing.T) {
	dir := t.TempDir()
	handwritten := filepath.Join(dir, "helpers.go")
	if err := os.WriteFile(handwritten, []byte(gen.Header("dev")+"\n\npackage models\n"), 0o600); err != nil {
		t.Fatalf("seeding: %v", err)
	}

	stale, err := gen.StaleFiles(dir, nil)
	if err != nil {
		t.Fatalf("StaleFiles() unexpected error: %v", err)
	}
	if len(stale) != 0 {
		t.Errorf("StaleFiles() = %v, want empty — only *_gen.go is considered", stale)
	}
}

// TestHeader_CarriesTheProvenancePrefix ties emission to the check. StaleFiles
// deletes on the strength of GeneratedHeaderPrefix, so a Header that stopped
// starting with it would make the sweep stop recognizing sqlgen's own output.
func TestHeader_CarriesTheProvenancePrefix(t *testing.T) {
	got := gen.Header("v1.2.0")
	if want := gen.GeneratedHeaderPrefix + "v1.2.0. DO NOT EDIT."; got != want {
		t.Errorf("Header(%q) = %q, want %q", "v1.2.0", got, want)
	}
}
