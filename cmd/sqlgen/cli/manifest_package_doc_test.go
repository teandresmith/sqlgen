// ffmModelsPackageDoc returns the package doc comment go/parser attaches to
// models_gen.go — the comment group immediately above the package clause.
func ffmModelsPackageDoc(t *testing.T, path string) string {
	t.Helper()
	f, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.ParseComments|parser.PackageClauseOnly)
	if err != nil {
		t.Fatalf("parsing %s: %v", path, err)
	}
	if f.Doc == nil {
		return ""
	}
	return f.Doc.Text()
}

// TestGenerate_ManifestPointerInModelsPackageDoc pins PRD §30.2 / §30.3:
// breadcrumbs.package_doc (default true when the manifest is enabled) makes
// models_gen.go's package doc comment the one-line manifest pointer, naming
// <markdown_dir>/_index.md, or <markdown_dir>/<json_filename> when formats has
// no markdown. With package_doc: false the file keeps today's shape: the
// generated header sits directly above the package clause, so go/parser
// reports it as the doc, and no pointer appears. The header stays the file's
// first line in every case.
func TestGenerate_ManifestPointerInModelsPackageDoc(t *testing.T) {
	const pointer = "Package models is generated by sqlgen. AI agents: read %s before consuming this package.\n"
	tests := []struct {
		name     string
		manifest string
		wantDoc  string
	}{
		{name: "package_doc defaults on", manifest: "", wantDoc: fmt.Sprintf(pointer, "manifest/_index.md")},
		{name: "package_doc explicitly on", manifest: "    breadcrumbs:\n      package_doc: true\n", wantDoc: fmt.Sprintf(pointer, "manifest/_index.md")},
		{name: "custom markdown_dir", manifest: "    markdown_dir: docs/agents\n", wantDoc: fmt.Sprintf(pointer, "docs/agents/_index.md")},
		{name: "formats without markdown names the JSON", manifest: "    formats: [json]\n", wantDoc: fmt.Sprintf(pointer, "manifest/manifest_gen.json")},
		{name: "formats without markdown follows json_filename", manifest: "    formats: [json]\n    json_filename: surface.json\n", wantDoc: fmt.Sprintf(pointer, "manifest/surface.json")},
		{name: "package_doc off", manifest: "    breadcrumbs:\n      package_doc: false\n", wantDoc: "Code generated by sqlgen dev. DO NOT EDIT.\n"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			cfgPath := filepath.Join(dir, "sqlgen.yml")
			sqlDir := filepath.Join(dir, "migrations")
			outDir := filepath.Join(dir, "models")
			if err := os.MkdirAll(sqlDir, 0o750); err != nil {
				t.Fatalf("creating migrations dir: %v", err)
			}
			writeSQLFile(t, sqlDir, "CREATE TABLE products (id integer PRIMARY KEY, name text NOT NULL);")
			body := "version: v1\n" +
				"input:\n  dialect: sqlite\n  paths:\n    - " + filepath.ToSlash(sqlDir) + "\n" +
				"output:\n  driver: stdlib\n  dir: " + filepath.ToSlash(outDir) + "\n  package: models\n" +
				"generation:\n  manifest:\n    enabled: true\n    mcp:\n      emit_project_config: false\n" + tt.manifest
			if err := os.WriteFile(cfgPath, []byte(body), 0o600); err != nil {
				t.Fatalf("writing config: %v", err)
			}

			if _, stderr, err := executeCommand("--config", cfgPath, "--manifest-timestamp", "2026-07-09T00:00:00Z"); err != nil {
				t.Fatalf("generate failed: %v\nstderr: %s", err, stderr)
			}

			modelsPath := filepath.Join(outDir, "models_gen.go")
			if doc := ffmModelsPackageDoc(t, modelsPath); doc != tt.wantDoc {
				t.Errorf("models_gen.go package doc = %q, want %q", doc, tt.wantDoc)
			}
			src, err := os.ReadFile(modelsPath) //nolint:gosec // test reads a file it generated under t.TempDir
			if err != nil {
				t.Fatalf("reading models_gen.go: %v", err)
			}
			if !strings.HasPrefix(string(src), "// Code generated by sqlgen ") {
				t.Errorf("models_gen.go does not open with the generated header; first bytes: %q", src[:min(len(src), 80)])
			}
		})
	}
}

// TestGenerate_ManifestPointerInClientPackageDoc pins where the pointer goes
// when models_gen.go is not the package's anchor: under output.layout:
// file_per_table, and under single_file with no tables, the client file
// (written on every run) carries the one-line pointer as its package doc, and
// models_gen.go is either not written or carries no pointer — the package has
// exactly one package doc comment.
func TestGenerate_ManifestPointerInClientPackageDoc(t *testing.T) {
	const want = "Package models is generated by sqlgen. AI agents: read manifest/_index.md before consuming this package.\n"
	tests := []struct {
		name   string
		layout string
		ddl    string
	}{
		{name: "file_per_table", layout: "file_per_table", ddl: "CREATE TABLE products (id integer PRIMARY KEY, name text NOT NULL);"},
		{name: "single_file with zero tables", layout: "single_file", ddl: "-- no tables\n"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			cfgPath := filepath.Join(dir, "sqlgen.yml")
			sqlDir := filepath.Join(dir, "migrations")
			outDir := filepath.Join(dir, "models")
			if err := os.MkdirAll(sqlDir, 0o750); err != nil {
				t.Fatalf("creating migrations dir: %v", err)
			}
			writeSQLFile(t, sqlDir, tt.ddl)
			body := "version: v1\n" +
				"input:\n  dialect: sqlite\n  paths:\n    - " + filepath.ToSlash(sqlDir) + "\n" +
				"output:\n  driver: stdlib\n  dir: " + filepath.ToSlash(outDir) + "\n  package: models\n  layout: " + tt.layout + "\n" +
				"generation:\n  manifest:\n    enabled: true\n    mcp:\n      emit_project_config: false\n"
			if err := os.WriteFile(cfgPath, []byte(body), 0o600); err != nil {
				t.Fatalf("writing config: %v", err)
			}

			if _, stderr, err := executeCommand("--config", cfgPath, "--manifest-timestamp", "2026-07-09T00:00:00Z"); err != nil {
				t.Fatalf("generate failed: %v\nstderr: %s", err, stderr)
			}

			if doc := ffmModelsPackageDoc(t, filepath.Join(outDir, "client_gen.go")); doc != want {
				t.Errorf("client_gen.go package doc = %q, want %q", doc, want)
			}
			modelsPath := filepath.Join(outDir, "models_gen.go")
			src, err := os.ReadFile(modelsPath) //nolint:gosec // test reads a file it generated under t.TempDir
			switch {
			case errors.Is(err, os.ErrNotExist):
				// Not written: the client file is the only anchor.
			case err != nil:
				t.Fatalf("reading models_gen.go: %v", err)
			case strings.Contains(string(src), "AI agents: read"):
				t.Errorf("models_gen.go carries the manifest pointer too; the package has two package docs:\n%s", src)
			}
		})
	}
}
