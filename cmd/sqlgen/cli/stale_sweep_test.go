// The stale sweep, at the CLI level. It once deleted any orphaned *_gen.go
// on the suffix alone; output.dir defaults to the module root, where
// other generators' _gen.go files ordinarily live.

// TestDiff_ForeignGenFileNotReportedDeleted pins the provenance rule on the
// preview path too. `sqlgen diff` shares gen.StaleFiles with the sweep, so a
// consumer's wire_gen.go must neither be reported as a pending deletion nor
// make diff exit non-zero — the preview would otherwise promise a deletion the
// generator no longer performs.
func TestDiff_ForeignGenFileNotReportedDeleted(t *testing.T) {
	dir := t.TempDir()
	cfgPath := filepath.Join(dir, "sqlgen.yml")
	sqlDir := filepath.Join(dir, "migrations")
	if err := os.MkdirAll(sqlDir, 0o750); err != nil {
		t.Fatalf("creating migrations dir: %v", err)
	}
	outputDir := filepath.Join(dir, "output")
	writeTestConfigWithDir(t, cfgPath, sqlDir, outputDir) // file_per_table
	writeSQLFile(t, sqlDir, "CREATE TABLE users (id serial PRIMARY KEY, name text NOT NULL);")

	if _, _, err := executeCommand("generate", "--config", cfgPath); err != nil {
		t.Fatalf("generate failed: %v", err)
	}

	// Another generator's output, living in the same package directory.
	foreign := filepath.Join(outputDir, "wire_gen.go")
	if err := os.WriteFile(foreign, []byte("// Code generated by Wire. DO NOT EDIT.\n\npackage models\n"), 0o600); err != nil {
		t.Fatalf("writing foreign generated file: %v", err)
	}

	stdout, _, err := executeCommand("diff", "--config", cfgPath)
	if strings.Contains(stdout, "wire_gen.go") {
		t.Errorf("diff reported another generator's file as a pending change\n--- stdout ---\n%s", stdout)
	}
	if err != nil {
		t.Errorf("diff reported changes for a clean tree holding a foreign _gen.go: %v\n--- stdout ---\n%s", err, stdout)
	}

	if _, statErr := os.Stat(foreign); statErr != nil {
		t.Errorf("diff must not delete anything, but wire_gen.go is gone: %v", statErr)
	}
}

// TestGenerate_ForeignGenFileSurvivesSweep is the same protection on the path
// that actually deletes: `sqlgen generate` under file_per_table sweeps orphaned
// *_gen.go files, and output.dir defaults to the module root, where wire and
// mockgen output ordinarily lives.
func TestGenerate_ForeignGenFileSurvivesSweep(t *testing.T) {
	dir := t.TempDir()
	cfgPath := filepath.Join(dir, "sqlgen.yml")
	sqlDir := filepath.Join(dir, "migrations")
	if err := os.MkdirAll(sqlDir, 0o750); err != nil {
		t.Fatalf("creating migrations dir: %v", err)
	}
	outputDir := filepath.Join(dir, "output")
	writeTestConfigWithDir(t, cfgPath, sqlDir, outputDir) // file_per_table
	writeSQLFile(t, sqlDir, "CREATE TABLE users (id serial PRIMARY KEY, name text NOT NULL);")

	if _, _, err := executeCommand("generate", "--config", cfgPath); err != nil {
		t.Fatalf("first generate failed: %v", err)
	}

	foreign := filepath.Join(outputDir, "mock_gen.go")
	if err := os.WriteFile(foreign, []byte("// Code generated by MockGen. DO NOT EDIT.\n\npackage models\n"), 0o600); err != nil {
		t.Fatalf("writing foreign generated file: %v", err)
	}

	// A sqlgen-authored orphan alongside it, to prove the sweep still works.
	orphan := filepath.Join(outputDir, "dropped_table_gen.go")
	if err := os.WriteFile(orphan, []byte(gen.Header("dev")+"\n\npackage models\n"), 0o600); err != nil {
		t.Fatalf("writing sqlgen orphan: %v", err)
	}

	if _, stderr, err := executeCommand("generate", "--config", cfgPath); err != nil {
		t.Fatalf("second generate failed: %v\nstderr: %s", err, stderr)
	}

	if _, err := os.Stat(foreign); err != nil {
		t.Errorf("sqlgen deleted another generator's mock_gen.go: %v", err)
	}
	if _, err := os.Stat(orphan); !os.IsNotExist(err) {
		t.Errorf("sqlgen's own orphaned _gen.go survived the sweep (stat err = %v) — provenance gating must not disable cleanup", err)
	}
}
