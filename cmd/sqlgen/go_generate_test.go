package main_test

import (
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
	"testing"
)

// TestGoGenerate_DirectiveRunsCodeGeneration builds the sqlgen binary, puts
// it on PATH, and runs `go generate ./...` in a fresh module whose only Go
// file carries a `//go:generate sqlgen generate` directive beside a
// sqlgen.yml. The generated package appears with sqlgen's header; nothing
// beyond the directive and the standard toolchain is involved.
func TestGoGenerate_DirectiveRunsCodeGeneration(t *testing.T) {
	if testing.Short() {
		t.Skip("builds the sqlgen binary and runs go generate; skipped in short mode")
	}
	goBin, err := exec.LookPath("go")
	if err != nil {
		t.Skip("go toolchain not on PATH")
	}

	binDir := t.TempDir()
	exe := "sqlgen"
	if runtime.GOOS == "windows" {
		exe += ".exe"
	}
	build := exec.CommandContext(t.Context(), goBin, "build", "-o", filepath.Join(binDir, exe), ".") //nolint:gosec // the go binary from PATH, output into a t.TempDir
	if out, err := build.CombinedOutput(); err != nil {
		t.Fatalf("building sqlgen: %v\n%s", err, out)
	}

	project := t.TempDir()
	files := map[string]string{
		"go.mod":      "module example.com/app\n\ngo 1.27\n",
		"generate.go": "// Package app holds the go:generate directive.\npackage app\n\n//go:generate sqlgen generate\n",
		"schema.sql":  "CREATE TABLE notes (id INTEGER PRIMARY KEY AUTOINCREMENT, body TEXT NOT NULL);\n",
		"sqlgen.yml": `version: v1
input:
  dialect: sqlite
  paths:
    - ./schema.sql
output:
  driver: stdlib
  dir: ./db
  package: db
  layout: single_file
`,
	}
	for name, body := range files {
		if err := os.WriteFile(filepath.Join(project, name), []byte(body), 0o600); err != nil {
			t.Fatalf("writing %s: %v", name, err)
		}
	}
	models := filepath.Join(project, "db", "models_gen.go")
	if _, err := os.Stat(models); !os.IsNotExist(err) {
		t.Fatalf("control: %s exists before go generate ran (stat error %v)", models, err)
	}

	run := exec.CommandContext(t.Context(), goBin, "generate", "./...") //nolint:gosec // the go binary from PATH, run on a test-written temp module
	run.Dir = project
	run.Env = append(os.Environ(),
		"PATH="+binDir+string(os.PathListSeparator)+os.Getenv("PATH"),
		"GOWORK=off", "GOFLAGS=-mod=mod", "GOTOOLCHAIN=local",
	)
	if out, err := run.CombinedOutput(); err != nil {
		t.Fatalf("go generate ./...: %v\n%s", err, out)
	}

	body, err := os.ReadFile(models) //nolint:gosec // reading back a t.TempDir go generate wrote into
	if err != nil {
		t.Fatalf("go generate ran but produced no %s: %v", models, err)
	}
	if !strings.HasPrefix(string(body), "// Code generated by sqlgen ") {
		first, _, _ := strings.Cut(string(body), "\n")
		t.Errorf("%s starts with %q, want sqlgen's generated-file header", models, first)
	}
	if !strings.Contains(string(body), "type Note struct") {
		t.Errorf("%s declares no Note entity; the schema was not generated", models)
	}
}
